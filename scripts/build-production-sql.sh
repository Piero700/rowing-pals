#!/bin/zsh
# Builds docs/production/production-setup.sql: everything a brand-new, empty Supabase project
# needs to match staging, in one file to paste into the SQL editor.
#
#   docs/schema.sql already holds every change up to 2026-10-15 (each migration up to then also
#   updated it). Every migration from 2026-10-16 on was only run on staging, so they follow it,
#   in the order they were written (commit order, not filename order: by filename,
#   coach-notepad-np3 would sort before coach-notepad, which it depends on).
#
#   Left out on purpose: 2026-11-05-delete-all-clubs.sql (a one-off wipe of staging's clubs,
#   nothing to wipe on a new project).
#
# Run it again whenever a new migration lands, then commit the regenerated file:
#   zsh scripts/build-production-sql.sh
# A new migration must be added to MIGRATIONS below, in order.

set -euo pipefail
cd "$(dirname "$0")/.."

MIGRATIONS=(
  2026-10-16-coach-version.sql
  2026-10-16-calendar.sql
  2026-10-16-boats.sql
  2026-10-17-rigging-and-announcements.sql
  2026-10-18-coxed-quad.sql
  2026-10-18-cox-side.sql
  2026-10-18-water-session-ends.sql
  2026-10-18-usernames.sql
  2026-10-18-boat-colours.sql
  2026-10-18-rank-change-alerts.sql
  2026-10-18-crew-tags.sql
  2026-10-18-challenges-and-erg-events.sql
  2026-10-18-season-wrapped.sql
  2026-11-03-mutual-follow-posts.sql
  2026-11-05-coach-notepad.sql
  2026-11-05-coach-notepad-np3.sql
  2026-11-05-coach-notepad-np4.sql
  2026-11-05-edit-workout.sql
  2026-11-05-clubs-open-and-verified.sql
  2026-11-13-automatic-leaderboards.sql
  2026-11-13-performance-indexes.sql
  2026-11-17-private-posts.sql
  2026-11-17-minimum-age.sql
  2026-11-17-verification-admin.sql
)
SKIPPED=(2026-11-05-delete-all-clubs.sql)

# Every migration file after 2026-10-15 must be listed or skipped, so a new one can't be forgotten.
for f in docs/migrations/*.sql; do
  name=${f:t}
  [[ $name < 2026-10-16 ]] && continue
  if (( ! ${MIGRATIONS[(Ie)$name]} && ! ${SKIPPED[(Ie)$name]} )); then
    echo "error: $name is not in MIGRATIONS or SKIPPED in scripts/build-production-sql.sh" >&2
    exit 1
  fi
done

OUT=docs/production/production-setup.sql
mkdir -p docs/production
{
  echo "-- ================================================================================"
  echo "-- Rowing Pals: PRODUCTION database setup. GENERATED by scripts/build-production-sql.sh"
  echo "-- Do not edit by hand: edit docs/schema.sql or docs/migrations/ and re-run the script."
  echo "--"
  echo "-- Run ONCE, on a brand-new EMPTY production project, in the Supabase SQL editor."
  echo "-- Never run it on staging (staging already has all of this)."
  echo "-- Step-by-step: docs/production/app-store-launch.md, section 2."
  echo "-- ================================================================================"
  echo
  echo "-- Photo buckets (staging's were made in the dashboard). Private: the rules in"
  echo "-- docs/schema.sql decide who may see each photo."
  echo "insert into storage.buckets (id, name, public) values"
  echo "  ('monitors', 'monitors', false),"
  echo "  ('selfies', 'selfies', false)"
  echo "on conflict (id) do nothing;"
  echo
  echo
  echo "-- ################################################################################"
  echo "-- docs/schema.sql (everything up to 2026-10-15)"
  echo "-- ################################################################################"
  cat docs/schema.sql
  for m in $MIGRATIONS; do
    echo
    echo
    echo "-- ################################################################################"
    echo "-- docs/migrations/$m"
    echo "-- ################################################################################"
    cat docs/migrations/$m
  done
  echo
  echo
  echo "-- Done. Next: section 2, step 5 of docs/production/app-store-launch.md (make yourself admin)."
} > $OUT

echo "Wrote $OUT ($(wc -l < $OUT | tr -d ' ') lines, schema + ${#MIGRATIONS} migrations)"
