# Fields the Swift port must match. Numbers compare within tolerance; flags compare as a
# set; strings exactly. Warnings and recommendation TEXT are deliberately excluded —
# the app owns its copy, and the flags carry the meaning.
NUMERIC_COMPONENTS = ("anchor_split", "paul_adjustment", "intensity_offset",
                      "rpe_correction", "two_k_equivalent", "projection_to_target",
                      "weight_trend_correction", "volume_modifier", "clamp_adjustment",
                      "population_2k_seconds")


def expected_view(result: dict) -> dict:
    anchor = result.get("anchor")
    interp = result.get("interpretation") or {}
    wa, ag = interp.get("weight_adjusted"), interp.get("age_graded")
    return {
        "predicted_split_seconds": result["predicted_split_seconds"],
        "predicted_total_time_seconds": result["predicted_total_time_seconds"],
        "predicted_split_formatted": result["predicted_split_formatted"],
        "predicted_total_time_formatted": result["predicted_total_time_formatted"],
        "predicted_split_range_seconds": result["predicted_split_range_seconds"],
        "predicted_total_time_range_seconds": result["predicted_total_time_range_seconds"],
        "confidence_score": result["confidence_score"],
        "confidence_numeric": result["confidence_numeric"],
        "anchor_tier": anchor["tier"] if anchor else None,
        "anchor_method": anchor["method"] if anchor else None,
        "anchor_session_ids": anchor["session_ids"] if anchor else None,
        "components": {k: v for k, v in (result.get("components") or {}).items()
                       if k in NUMERIC_COMPONENTS and v is not None},
        "load_trimp_lite": result["load"]["trimp_lite"],
        "load_modifier_seconds": result["load"]["modifier_seconds"],
        "spread_seconds": result["diagnostics"]["spread_seconds"],
        "two_k_equivalent_by_tier": result["diagnostics"]["two_k_equivalent_by_tier"],
        "weight_adjusted_total_seconds": wa["total_time_seconds"] if wa else None,
        "age_graded_total_seconds": ag["total_time_seconds"] if ag else None,
        "flags": sorted(set(result["flags"])),
    }


def build() -> dict:
    vectors = []
    for case in CASES:
        config = replace(pe.DEFAULT_CONFIG, **case.get("config_overrides", {}))
        result = pe.predict_test_piece(case["history"], case["target"], AS_OF, config,
                                       athlete=case.get("athlete"))
        json.dumps(result)  # must be serialisable
        vectors.append({
            "name": case["name"],
            "as_of": AS_OF.isoformat(),
            "target_distance_m": case["target"],
            "config_overrides": case.get("config_overrides", {}),
            "athlete": case.get("athlete"),
            "history": case["history"],
            "expected": expected_view(result),
        })

    parsing = {
        "format_seconds": [{"in": v, "out": pe.format_seconds(v)}
                           for v in (0.4, 59.96, 105.0, 419.96, 421.2, 3599.99, 5025.6)],
        "weight_adjustment_factor": [{"weight_kg": w,
                                      "out": round(pe.weight_adjustment_factor(w), 10)}
                                     for w in (55.0, 68.0, 80.0, 100.0, 122.47)],
        "age_performance_factor": [{"age": a,
                                    "out": round(pe.age_performance_factor(a), 10)}
                                   for a in (12, 16, 18, 22, 27, 30, 35, 40, 50, 55, 70,
                                             85)],
        "normalise_rpe": [{"in": v, "out": pe._normalise_rpe(v)}
                          for v in (0, 3, 7.5, 10, 10.5, 11, 15, 20, 20.5, -1)],
    }

    return {
        "schema_version": pe.SCHEMA_VERSION,
        "generated_from": "pace_engine.py (Python reference implementation)",
        "tolerance": {
            "seconds": 0.02,
            "note": "Python rounds half-to-even, Swift's .rounded() half-away-from-zero. "
                    "Compare numbers within 0.02, not for exact equality.",
        },
        "config": {k: v for k, v in asdict(pe.DEFAULT_CONFIG).items()},
        "tiers": {k: asdict(v) for k, v in pe.TIERS.items()},
        "cases": vectors,
        "parsing": parsing,
    }


if __name__ == "__main__":
    data = build()
    with open("golden_vectors.json", "w") as fh:
        json.dump(data, fh, indent=2)
    print(f"wrote golden_vectors.json: {len(data['cases'])} cases, "
          f"{sum(len(v) for v in data['parsing'].values())} parsing checks")
