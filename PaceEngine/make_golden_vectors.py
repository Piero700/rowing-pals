AS_OF = date(2026, 9, 17)


def day(n: int) -> str:
    return (AS_OF - timedelta(days=n)).isoformat()


def coherent_history(s2k: float = 105.0) -> list[dict]:
    """Every session generated by the forward model, so all tiers agree on S2k."""
    rows = []
    plan = [("UT2", 16000, 19), ("UT2", 14000, 20), ("UT1", 12000, 22),
            ("AT", 8000, 26), ("UT2", 18000, 18)]
    for week in range(4):
        for offset, (tag, dist, rate) in enumerate(plan):
            split = round(pe._pace_for(tag, dist, s2k), 1)
            rows.append({"id": f"w{week}-{offset}", "date": day(week * 7 + offset),
                         "distance_m": dist, "split_s": split,
                         "time_s": round(split * dist / 500.0, 1),
                         "stroke_rate": rate, "tag": tag})
    tr = pe._pace_for("TR", 6000, s2k)
    rows.append({"id": "6k-tr", "date": day(9), "distance_m": 6000,
                 "time_s": round(tr * 6000 / 500.0, 1), "stroke_rate": 30, "tag": "TR"})
    return rows


def ut2_rows(n: int, rpe=None, distance=16000, split=127.0) -> list[dict]:
    rows = [{"id": f"u{i}", "date": day(i), "distance_m": distance, "split_s": split,
             "stroke_rate": 19, "tag": "UT2"} for i in range(1, n + 1)]
    if rpe is not None:
        for r in rows:
            r["rpe"] = rpe
    return rows


def with_weights(rows: list[dict], start_kg: float, end_kg: float) -> list[dict]:
    out = [dict(r) for r in rows]
    for r in out:
        days_ago = (AS_OF - pe.parse_date(r["date"])).days
        r["bodyweight_kg"] = round(end_kg + (start_kg - end_kg) * days_ago / 30.0, 3)
    return out


def tired(rows: list[dict]) -> list[dict]:
    out = [dict(r) for r in rows]
    for r in out:
        if r["tag"] == "UT2" and (AS_OF - pe.parse_date(r["date"])).days <= 7:
            r["rpe"] = 5.5
    return out


